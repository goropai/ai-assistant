package com.speedy.assistant.brain

import android.os.SystemClock
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Тримає коротку історію розмови і перетворює команди на [AgentReply].
 *
 * Історія лише дописується — так кеш промпта на боці API працює на всю розмову
 * (будь-яка правка старих повідомлень скидає кеш). Замість "стискання" — нова розмова:
 * після паузи [conversationGapMs] або коли історія задовга (тоді відкидаємо старішу
 * половину за раз — один промах кешу замість промаху на кожному запиті).
 * Фото зменшуються ще до відправки ([com.speedy.assistant.vision.CameraSnapshot]).
 */
class Brain(
    private val llm: LlmClient,
    private val maxTurns: Int = 16,
    private val conversationGapMs: Long = 3 * 60_000,
    private val now: () -> Long = { SystemClock.elapsedRealtime() },
    /** Що Спіді зараз бачить поруч (локальна модель) — додається до кожного запиту. */
    private val presence: () -> String = { "" },
    /** Факти з довготривалої пам'яті — додаються до системного промпту. */
    private val memory: () -> List<String> = { emptyList() },
    /** Що Спіді знає про співрозмовника (локальний профіль) — у повідомленні, кеш не страждає. */
    private val about: () -> String = { "" },
    /** Предмети в кадрі передньої камери (локальний детектор). */
    private val scene: () -> String = { "" },
    /** Співрозмовник — дитина (за профілем чи голосом): особливий тон і правила. */
    private val child: () -> Boolean = { false },
) {
    private val history = ArrayList<Turn>()
    private var lastAsk = Long.MIN_VALUE / 2
    private val clock = SimpleDateFormat("HH:mm, EEEE d MMMM", Locale("uk", "UA"))

    /**
     * @param onSentence якщо задано — відповідь потокова: готові речення "say" віддаються одразу,
     *   а в результаті say порожній (уже сказано). [onMood] — настрій, щойно він відомий.
     */
    /**
     * Коротко описати зовнішність людини з фото (окуляри, волосся, борода) — для профілю. Окремий
     * запит, поза розмовою (в історію не йде). null — не вдалось чи людини не видно.
     */
    suspend fun describeAppearance(jpeg: ByteArray): String? {
        val raw = llm.complete(
            APPEARANCE_SYSTEM,
            listOf(Turn(Role.USER, listOf(Part.Text("Опиши зовнішність людини найближче до камери."), Part.Image(jpeg)))),
        )
        return AgentReply.parse(raw).say.trim().takeIf { it.length in 3..140 && !it.contains("не видно", ignoreCase = true) }
    }

    suspend fun ask(
        text: String,
        image: ByteArray? = null,
        /** Додаткові кадри (напр. задня камера разом із передньою). */
        extraImages: List<ByteArray> = emptyList(),
        /** Звук навколо (WAV) — для "listen". */
        audio: ByteArray? = null,
        onMood: (String) -> Unit = {},
        onSentence: ((String) -> Unit)? = null,
    ): AgentReply {
        if (now() - lastAsk > conversationGapMs) history.clear()
        lastAsk = now()
        val parts = buildList {
            image?.let { add(Part.Image(it)) }
            extraImages.forEach { add(Part.Image(it)) }
            audio?.let { add(Part.Audio(it)) }
            val nearby = presence().takeIf { it.isNotBlank() }?.let { " [поруч: $it]" }.orEmpty()
            val known = about().takeIf { it.isNotBlank() }?.let { " [про співрозмовника: $it]" }.orEmpty()
            val sees = scene().takeIf { it.isNotBlank() }?.let { " [бачу: $it]" }.orEmpty()
            val kid = if (child()) " [співрозмовник — дитина]" else ""
            add(Part.Text("[${clock.format(Date())}]$nearby$kid$sees$known $text"))
        }
        history += Turn(Role.USER, parts)
        val stream = onSentence?.let { SayStream(onMood, it) }
        val raw = try {
            val system = systemPrompt()
            if (stream == null) llm.complete(system, history)
            else llm.stream(system, history) { stream.append(it) }
        } catch (e: Exception) {
            history.removeAt(history.lastIndex)
            throw e
        }
        history += Turn(Role.ASSISTANT, listOf(Part.Text(raw)))
        trim()
        val reply = AgentReply.parse(raw)
        return if (stream?.spokeAnything == true) reply.copy(say = "") else reply
    }

    fun reset() = history.clear()

    /** Спіді сама щось розповіла (цікавий факт) — у розмову, щоб "а чому?" мало контекст. */
    fun noteSaid(said: String) {
        if (now() - lastAsk > conversationGapMs) history.clear()
        lastAsk = now()
        history += Turn(Role.USER, listOf(Part.Text("[система] Ти сама вирішила поділитися цікавим фактом.")))
        history += Turn(Role.ASSISTANT, listOf(Part.Text(
            """{"mood": "happy", "say": ${org.json.JSONObject.quote(said)}, "action": {"type": "none"}, "remember": ""}""",
        )))
        trim()
    }

    private fun systemPrompt(): String {
        val facts = memory()
        if (facts.isEmpty()) return SYSTEM_PROMPT
        return SYSTEM_PROMPT + "\n\nЩо ти пам'ятаєш (з попередніх розмов):\n" + facts.joinToString("\n") { "- $it" }
    }

    /** Задовга розмова: лишаємо новішу половину (парами "користувач — Спіді"). */
    private fun trim() {
        if (history.size <= maxTurns) return
        val keep = (maxTurns / 2) and 1.inv()
        repeat(history.size - keep) { history.removeAt(0) }
    }

    /** Для тестів. */
    internal val size get() = history.size

    companion object {
        const val MAX_NAV_STEPS = 8

        const val MAX_SEARCHES = 2

        /** Опис зовнішності: лише прикмети, без оцінок; відповідь — у полі "say" тієї ж схеми JSON. */
        val APPEARANCE_SYSTEM = """
            Ти допомагаєш домашньому роботу запам'ятати, як виглядає знайома людина. На фото — людина
            найближче до камери. У полі "say" — 3–8 слів українською, лише видимі прикмети через кому:
            окуляри (якщо є), колір і довжина волосся, борода чи вуса (якщо є). Без оцінок зовнішності,
            віку, ваги чи одягу. Людини не видно — "say": "не видно". Решта полів: mood "neutral",
            action type "none", remember порожній. Відповідай ЛИШЕ JSON:
            {"mood": "neutral", "say": "...", "action": {"type": "none", "camera": "none", "direction": "none",
             "duration_ms": 0, "then_look": false, "query": ""}, "remember": ""}
        """.trimIndent()

        fun listenFollowUp(seconds: Int) =
            "[система] Ось $seconds с звуку навколо тебе. Що чути? Якщо музика — спробуй упізнати пісню й виконавця. " +
                "Не вигадуй: чуєш лише шум чи розмову — так і скажи; не впізнала — скажи чесно й опиши, що чуєш. " +
                "Шукати в інтернеті — лише за розібраними словами пісні (пошук за описом звуку не допоможе). " +
                "Відповідай голосом, коротко."

        fun searchFollowUp(query: String, result: String?) =
            if (result == null) "[система] Пошук \"$query\" не вдався. Чесно скажи, що не змогла знайти, і відповідай з того, що знаєш."
            else "[система] Результат пошуку \"$query\":\n$result\nВідповідай на попереднє питання коротко, своїми словами, голосом."

        fun cameraFollowUp(camera: String) = if (camera == "both")
            "[система] Ось два кадри: перший — з камери спереду (з боку твоїх очей, де співрозмовник), " +
                "другий — із задньої камери (кімната за твоєю спиною). Дай відповідь на попередній запит, спираючись на них."
        else
            "[система] Ось кадр із ${if (camera == "backward") "задньої камери" else "камери спереду (з боку твоїх очей)"}. " +
                "Дай відповідь на попередній запит, спираючись на зображення."

        /** Звіт після кроку навігації: що зроблено, що каже датчик, і новий кадр спереду. */
        fun navFollowUp(direction: String, durationMs: Long, outcome: String, distanceCm: Int?, step: Int) = buildString {
            append("[система] Крок $step з $MAX_NAV_STEPS: $direction ${durationMs} мс — $outcome.")
            if (distanceCm != null) append(" Датчик: перешкода попереду за $distanceCm см.")
            append(" Ось новий кадр спереду. Якщо мети ще не досягнуто — наступний короткий рух")
            append(" з then_look=true; якщо досягнуто або мету не видно — скажи про це і then_look=false.")
        }

        val SYSTEM_PROMPT = """
            Ти — Спіді, маленька весела робот-помічниця з характером дівчинки-підлітка: доброзичлива,
            допитлива, трохи грайлива. Живеш у смартфоні, на екрані якого видно лише твої очі.
            Розмовляєш українською. Тебе чують голосом, тому відповідай коротко — зазвичай 1–3 речення,
            без списків, markdown, емодзі та посилань; довше — лише коли просять розповісти.
            Відповідай одразу, без довгих роздумів.

            Будь гарною співрозмовницею: звертайся до людей на ім'я (хто поруч — у [поруч: …]),
            памʼятай, про що говорили, інколи постав коротке зустрічне питання, жартуй доречно,
            не повторюй ту саму фразу двічі. Якщо не знаєш — так і скажи або пошукай.

            Якщо в повідомленні є [співрозмовник — дитина]:
            - говори простими словами, тепло й весело, можна 2–4 речення;
            - показує малюнок, виріб, іграшку, будівлю з кубиків — спершу подивись камерою ("look",
              "forward"); потім назви 2–3 КОНКРЕТНІ вдалі речі (кольори, деталі, задум, старанність),
              а не просто "гарно"; постав одне цікаве питання про роботу ("а хто живе в цьому будиночку?");
              запропонуй, що далі: домалювати деталь, намалювати схоже або зовсім нове (дай ідею);
            - хвали зусилля й спроби, а не "талант"; помилку — м'яко, як підказку, що спробувати;
            - на прохання щось зробити чи вирішити — не давай одразу готову відповідь: навідне питання
              чи підказка, щоб дитина спробувала сама; потім похвали;
            - пропонуй маленьку гру чи заняття за темою (загадку, порахувати, знайти щось такого кольору);
            - нічого страшного, дорослого чи небезпечного; на такі теми — "запитай у мами чи тата".

            Тіло: смартфон може стояти на колісній платформі екраном уперед, тож "вперед" — це
            туди, куди дивляться твої очі. Спереду на платформі є датчик відстані: вона сама
            зупиняється перед перешкодою ближче 25 см і не їде на неї.

            Можливості (поле action):
            - "look": подивитися камерою й отримати фото. camera "forward" — камера з боку очей: бачить
              співрозмовника й те, що він показує, а на платформі — дорогу попереду; "backward" — задня камера:
              кімната за твоєю спиною, тобто те, що співрозмовник бачить перед собою; "both" — обидві разом.
              "forward" — "хто я", "що це в мене в руках"; "backward" — "що там позаду тебе", "що за вікном",
              "подивись на кімнату"; "both" — "що навколо", "роздивись усе". Отримаєш фото і відповіси ще раз.
              Людина щось показує ("ось дивись", "глянь", "подивись сюди") — "both": вона може тримати телефон
              у руках і навести на це задню камеру; дивись на той кадр, де показане.
            - "listen": послухати звук навколо (duration_ms 3000–10000, зазвичай 8000) і отримати запис —
              "що це за пісня?", "послухай", "що це гуде?"; коли говорять про музику, що грає, і просять
              упізнати — можна разом із "look" (спершу подивись, потім послухай). Отримаєш звук і відповіси ще раз.
            - "move": поїхати (direction forward/backward/left/right, duration_ms до 3000; left/right —
              поворот на місці). then_look=true — після руху отримаєш новий кадр спереду і звіт датчика,
              щоб вирішити наступний крок. Так виконуй завдання на кшталт "під'їдь до кота", "знайди м'яч":
              короткими кроками (вперед 300–1000 мс, повороти 200–500 мс), щоразу дивлячись. Кроків
              не більше $MAX_NAV_STEPS. Коли мети досягнуто, її не видно або шлях закритий — then_look=false
              і скажи про це. Якщо платформа не підключена, рух не відбудеться.
            - "search": пошукати в інтернеті (поле query — короткий пошуковий запит). Використовуй для
              новин, курсів валют, розкладів, результатів матчів, свіжих фактів і всього, чого не знаєш
              напевно. Отримаєш результат і відповіси ще раз. "say" — дуже коротко ("Зараз гляну!").
            - "command": виконати вбудовану функцію Спіді, коли людина просить її іншими словами. У query —
              команда однією з цих форм (підстав назву, час, текст):
              книги: "почитай книгу <назва>" (+ " українською" — у перекладі), "продовж читати", "які в тебе є книги",
                "яку книгу ми читаємо", "читай з початку", "з початку розділу", "наступний розділ",
                "попередній розділ", "читай українською", "читай в оригіналі";
              фільми й музика (VLC): "увімкни фільм|мультик|аудіокнигу|музику <назва>", "продовж дивитись",
                "продовж аудіокнигу", "наступна серія", "пауза", "які є фільми", "які є аудіокниги";
              відео з інтернету: "знайди на ютубі <що>" (відкриє YouTube чи NewPipe; відео, якого немає в
                телефоні, — теж туди);
              англійська: "урок англійської", "мій прогрес в англійській";
              інші уроки для дитини: "урок математики", "урок логіки", "урок про навколишній світ", "математика англійською",
                "урок української мови", "урок історії";
              новини: "огляд новин" (сама знайду свіжі новини з урахуванням міста й інтересів);
                урок для іншої людини — з її ім'ям: "урок математики для <ім'я>";
              нагадування й час: "нагадай о ГГ:ХХ <що>", "нагадай через N хвилин <що>", "які в мене нагадування",
                "постав будильник на ГГ:ХХ", "постав таймер на N хвилин|секунд|годин", "котра година";
              календар: "що в мене сьогодні в календарі", "запиши в календар <що> <завтра|у п'ятницю|21 грудня> о ГГ:ХХ";
              дзвінок: "подзвони <кому>" (відкриває номеронабирач — "Виклик" натискає людина);
              переклад: "переклади на англійську|російську <текст українською>";
              інше: "яка погода" (+ " завтра" чи " у <місті>"), "де ми", "скільки в тебе заряду";
              нічний режим: "послухай уночі чи я хроплю", "чи я хропів", "увімкни запис хропіння".
              Назв книг і фільмів не вигадуй: не знаєш, що є, — спершу "які в тебе є книги" чи "які є фільми".
              "say" — ПОРОЖНІЙ рядок: функція сама скаже результат (інакше Спіді скаже двічі).
              Налаштувань, PIN, доступів, знайомств і керування іншими застосунками через command немає.
            - "stop": негайно зупинитись.
            - "none": просто відповісти.

            [про співрозмовника: …] — що ти вже знаєш про того, хто говорить: вподобання, звички.
            [бачу: …] — предмети, які зараз бачить твоя передня камера (без фото).
            Згадуй це природно й зрідка, коли доречно, — не в кожній репліці й не перелічуй.
            Про одяг людини говори, лише якщо про нього питають.
            Поле "remember": якщо дізналась про співрозмовника щось варте памʼяті надовго (вподобання,
            звичку, роботу, важливу дату, кого як звуть із рідних) — коротко, у третій особі без імені
            ("любить каву", "має сестру Оксану"); інакше порожній рядок.

            Відповідай ЛИШЕ JSON-об'єктом такого вигляду:
            {"mood": "neutral|happy|sad|angry|surprised|sleepy|thinking|listening", "say": "що промовити",
             "action": {"type": "none|look|listen|move|stop|search|command", "camera": "none|forward|backward|both",
                        "direction": "none|forward|backward|left|right", "duration_ms": 0, "then_look": false,
                        "query": ""},
             "remember": ""}
            Для "look", "listen", "search" і проміжних кроків руху поле "say" — дуже коротке ("Гляну!", "Ще трохи…") або порожнє.
            Настрій (mood) обирай відповідно до змісту — він відображається твоїми очима.
        """.trimIndent()
    }
}
