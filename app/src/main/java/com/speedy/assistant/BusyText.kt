package com.speedy.assistant

/** Що казати, коли Спіді зайнята й довго мовчить: "ще працюю" — конкретно, якщо відомо чим. */
object BusyText {
    /** Перше оновлення — після стількох мс мовчання; далі — рідше. */
    const val FIRST_MS = 20_000L
    const val NEXT_MS = 45_000L

    /** [hint] — "Ще шукаю казку" (null — загально), [n] — котре оновлення за цю дію (з 0). */
    fun progress(hint: String?, n: Int): String = when (n) {
        0 -> hint?.let { "$it, хвилинку…" } ?: "Ще думаю, хвилинку…"
        1 -> hint?.let { "$it, ще трохи." } ?: "Ще працюю над цим, зачекай трохи."
        2 -> "Довго виходить. Якщо не хочеш чекати — торкнись мене."
        else -> hint?.let { "$it…" } ?: "Ще працюю…"
    }
}
